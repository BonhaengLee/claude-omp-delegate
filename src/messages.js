/**
 * User-facing text for result cards. Machine fields (status, code, data) never depend on the locale.
 * Locale: OMP_DELEGATE_LANG=en|ko, otherwise LC_ALL / LC_MESSAGES / LANG starting with "ko" selects Korean,
 * anything else selects English. Read at render time so tests and hosts can switch without reloading.
 */

export const LANG_ENV = 'OMP_DELEGATE_LANG';
export const LOCALES = /** @type {const} */ (['en', 'ko']);

/** @param {NodeJS.ProcessEnv} [env] @returns {'en'|'ko'} */
export function currentLocale(env = process.env) {
  const explicit = (env[LANG_ENV] ?? '').trim().toLowerCase();
  if (explicit === 'en' || explicit === 'ko') return explicit;
  const system = env.LC_ALL || env.LC_MESSAGES || env.LANG || '';
  return /^ko(?:[_.@-]|$)/i.test(system) ? 'ko' : 'en';
}

